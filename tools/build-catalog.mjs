#!/usr/bin/env node
// Builds assets/js/catalog.js from data/stock.csv.
// Edit the CSV (stock counts, prices, new rows), then run: node tools/build-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const csv = readFileSync(join(root, 'data/stock.csv'), 'utf8').trim().split(/\r?\n/);
const header = csv.shift().split(',');
const rows = csv.map((line) => {
  const cells = line.split(',');
  return Object.fromEntries(header.map((h, i) => [h, (cells[i] ?? '').trim()]));
});

const COLLECTIONS = {
  executive: {
    name: 'Executive',
    blurb: 'High-back upholstered chairs for directors, cabins and home studies.',
    describe: (p) => `${p.model} is a high-back upholstered executive chair with imported fittings throughout.`,
  },
  ergonomic: {
    name: 'Ergonomic',
    blurb: 'Supportive high-back chairs for long days at a desk.',
    describe: (p) => `${p.model} is an ergonomic high-back chair built for long working days, with imported fittings throughout.`,
  },
  task: {
    name: 'Task & office',
    blurb: 'Mid-back mesh chairs for teams, workstations and meeting rooms.',
    describe: (p) => `${p.model} is a mesh task chair for workstations and teams, with imported fittings throughout.`,
  },
  training: {
    name: 'Training',
    blurb: 'Chairs with a writing tablet for classrooms and training rooms.',
    describe: (p) => `${p.model} is a training chair with a writing tablet, suited to classrooms and seminar rooms.`,
  },
};

// Approximate swatch colours for the colour names used in the stock list.
const SWATCH = {
  silver: '#a9adb0', sand: '#c99a6b', ash: '#8d8c88', peach: '#e6c3a3', iron: '#5b4b48',
  'falk white': '#ece6da', black: '#1d1d1f', 'pearl white': '#efece4', bronze: '#a0603e',
  grey: '#8f9396', green: '#2f6b55', orange: '#d0603a', red: '#9e3434', blue: '#2f5d8a',
  khaki: '#a8996e', 'full black': '#111214', white: '#f2f2f0', brown: '#8a5232',
  'full mesh': '#6c6f73', 'grey / blue': '#4f7fae', 'black / green seat': '#2f6b55',
};

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const num = (s) => (s === '' ? null : Number(s));

const products = new Map();
for (const r of rows) {
  const key = slug(r.model);
  if (!products.has(key)) {
    products.set(key, {
      slug: key,
      model: r.model,
      collection: r.collection,
      warrantyYears: num(r.warranty_years),
      features: new Set(),
      variants: [],
    });
  }
  const p = products.get(key);
  if (r.features) p.features.add(r.features);
  p.variants.push({
    sku: `${r.model} ${r.colour}`,
    id: slug(`${r.model}-${r.colour}`),
    colour: r.colour,
    swatch: SWATCH[r.colour.toLowerCase()] ?? '#888888',
    stock: num(r.stock) ?? 0,
    image: r.image ? `assets/img/products/${r.image}` : null,
    price: num(r.price_bdt),
    salePrice: num(r.sale_price_bdt),
    sl: num(r.sl),
  });
}

const list = [...products.values()].map((p) => {
  const c = COLLECTIONS[p.collection];
  return {
    ...p,
    features: [...p.features],
    name: p.model,
    description: c.describe(p),
  };
});

const out = `// Generated by tools/build-catalog.mjs from data/stock.csv. Do not edit by hand.
window.DECOTURE_CATALOG = ${JSON.stringify(
  {
    stockListDate: '2026-10-20',
    collections: Object.fromEntries(
      Object.entries(COLLECTIONS).map(([k, v]) => [k, { name: v.name, blurb: v.blurb }])
    ),
    products: list,
  },
  null,
  1
)};
`;
writeFileSync(join(root, 'assets/js/catalog.js'), out);
console.log(`catalog.js: ${list.length} products, ${rows.length} variants`);
